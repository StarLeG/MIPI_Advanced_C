/**
 * @file integral.h
 * @brief Модуль для численного интегрирования функций
 * 
 * Реализует адаптивный метод Симпсона
 */

#ifndef INTEGRAL_H
#define INTEGRAL_H

#include "functions.h"

/**
 * @brief Структура для хранения результата интегрирования
 */
typedef struct {
    double result;      /**< Вычисленное значение интеграла */
    int iterations;     /**< Количество выполненных итераций (разбиений) */
    int success;        /**< Флаг успеха (1 - успешно, 0 - ошибка) */
} IntegralResult;

/**
 * @brief Численное интегрирование функции на отрезке [a, b]
 * 
 * Использует адаптивный метод Симпсона с автоматическим разбиением интервала
 * для достижения заданной точности.
 * 
 * @param f Интегрируемая функция
 * @param a Нижний предел интегрирования
 * @param b Верхний предел интегрирования
 * @param eps2 Требуемая точность вычисления интеграла
 * @return IntegralResult Структура с результатом интегрирования
 */
IntegralResult integral(func_ptr f, double a, double b, double eps2);

/**
 * @brief Запуск тестирования функций интегрирования
 * 
 * Вычисляет тестовые интегралы для всех трёх функций
 * и сравнивает с аналитическими значениями
 */
void test_integral(void);

#endif // INTEGRAL_H