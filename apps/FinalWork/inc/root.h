/**
 * @file root.h
 * @brief Модуль для поиска корней уравнений f(x) = g(x)
 * 
 * Реализует комбинированный метод секущих и бисекции
 */

#ifndef ROOT_H
#define ROOT_H

#include "functions.h"

/**
 * @brief Структура для хранения результата поиска корня
 */
typedef struct {
    double root;        /**< Найденный корень уравнения */
    int iterations;     /**< Количество выполненных итераций */
    int success;        /**< Флаг успеха (1 - корень найден, 0 - ошибка) */
} RootResult;

/**
 * @brief Поиск корня уравнения f(x) = g(x) на интервале [a, b]
 * 
 * Использует комбинацию метода секущих и метода бисекции для надежности.
 * Поиск прекращается при достижении точности eps1 по x или по значению функции.
 * 
 * @param f Первая функция
 * @param g Вторая функция
 * @param a Левая граница интервала
 * @param b Правая граница интервала
 * @param eps1 Требуемая точность поиска корня
 * @return RootResult Структура с результатом поиска
 */
RootResult root(func_ptr f, func_ptr g, double a, double b, double eps1);

/**
 * @brief Запуск тестирования функций поиска корня
 * 
 * Выполняет поиск всех трёх пересечений функций и выводит результаты
 */
void test_root(void);

#endif // ROOT_H